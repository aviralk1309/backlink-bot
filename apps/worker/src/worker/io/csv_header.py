"""M4-S3: header row and preamble detection for uploaded CSV files.

Rule: the header is the first non-blank record whose field count equals the
winning width from delimiter detection. Preamble lines ("Report generated by
...") have a different width, so they are skipped. For a single-column file
(width 0) the header is the first non-blank record.

``header_line`` is the 1-based PHYSICAL line where the header record starts,
the same meaning as header_line in fixtures/csv/manifest.json. It comes from
csv.reader.line_num, so quoted cells that span lines are counted correctly.

Limits (documented, not hidden):
  * A preamble line with the same field count as the data is taken as the
    header. The mapping screen (M4-S4) lets the user override the header line.
  * A file with no header row at all is reported through ``looks_like_data``.
    This module does not decide what to do about it.
  * Names are stripped of surrounding whitespace. Nothing else is changed.
"""

from __future__ import annotations

import csv
import io
from dataclasses import dataclass
from itertools import islice

MAX_SCAN_RECORDS = 200

_URL_PREFIXES = ("http://", "https://", "//", "www.")


@dataclass(frozen=True, slots=True)
class CsvHeader:
    # 1-based physical line of the header. None when the sample has no header.
    header_line: int | None
    # Header cells as written (stripped). May hold "" and repeated names.
    names: tuple[str, ...]
    # True when a header cell looks like a URL, so the file may have no header.
    looks_like_data: bool

    @property
    def preamble_lines(self) -> int:
        """Physical lines before the header (blank lines included)."""
        return 0 if self.header_line is None else self.header_line - 1

    @property
    def duplicate_names(self) -> tuple[str, ...]:
        seen: set[str] = set()
        dups: list[str] = []
        for name in self.names:
            if name and name in seen and name not in dups:
                dups.append(name)
            seen.add(name)
        return tuple(dups)

    @property
    def blank_columns(self) -> tuple[int, ...]:
        """0-based indexes of columns with an empty header."""
        return tuple(i for i, name in enumerate(self.names) if not name)

    @property
    def labels(self) -> tuple[str, ...]:
        """Unique display names. Blank becomes "Column N", repeats get "(2)"."""
        used: set[str] = set()
        out: list[str] = []
        for i, name in enumerate(self.names):
            base = name or f"Column {i + 1}"
            label, k = base, 2
            while label in used:
                label = f"{base} ({k})"
                k += 1
            used.add(label)
            out.append(label)
        return tuple(out)


_NO_HEADER = CsvHeader(None, (), False)


def _looks_like_url(cell: str) -> bool:
    return cell.strip().lower().startswith(_URL_PREFIXES)


def detect_header(text: str, delimiter: str, *, width: int) -> CsvHeader:
    """Find the header in a decoded text sample.

    ``width`` is DelimiterResult.width. Pass 0 for a single-column file.
    """
    target = width if width >= 2 else None
    reader = csv.reader(io.StringIO(text, newline=""), delimiter=delimiter)
    previous_end = 0
    try:
        for row in islice(reader, MAX_SCAN_RECORDS):
            start = previous_end + 1
            previous_end = reader.line_num
            if not any(cell.strip() for cell in row):
                continue  # blank line or a row of empty cells
            if target is None or len(row) == target:
                names = tuple(cell.strip() for cell in row)
                return CsvHeader(start, names, any(_looks_like_url(c) for c in names))
    except csv.Error:
        pass  # broken quoting before any header: report no header
    return _NO_HEADER
